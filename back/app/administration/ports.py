from typing import Protocol
from app.usage.models import PriceInput


class AdministrationReadPort(Protocol):
    def overview(self) -> dict: ...
    def users(self, q: str = "", offset: int = 0) -> list[dict]: ...
    def user_details(self, identifier: str) -> dict: ...
    def prices(self) -> list[dict]: ...


class TariffRepositoryPort(Protocol):
    def new_price(self, actor_id: str, price: PriceInput) -> dict: ...

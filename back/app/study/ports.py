from typing import Protocol


class StudyRepositoryPort(Protocol):
    def sets(self, owner_id: str) -> list[dict]: ...
    def study_set(self, identifier: str, owner_id: str) -> dict: ...
    def check_set_owner(self, identifier: str, owner_id: str) -> None: ...
    def save_set(self, result: dict, owner_id: str) -> dict: ...


class StudyExportPort(Protocol):
    async def __call__(self, result: dict) -> bytes: ...

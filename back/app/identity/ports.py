from typing import Protocol
from app.identity.models import AuthConfig


class SessionRepositoryPort(Protocol):
    def find_session(self, digest: str, now: int) -> dict | None: ...
    def revoke(self, digest: str) -> None: ...
    def store_flow(self, values: tuple, previous: str | None, now: int) -> None: ...
    def consume_flow(self, digest: str) -> dict | None: ...
    def create(
        self,
        claims: dict,
        name: str,
        digest: str,
        previous: str | None,
        now: int,
        stamp: str,
        lifetime: int,
    ) -> str: ...


class IdentityProviderPort(Protocol):
    async def exchange(self, config: AuthConfig, code: str, verifier: str) -> str: ...
    def verify(self, encoded: str, nonce: str, client_id: str) -> dict: ...


class RolesPort(Protocol):
    def verified_login(self, identifier: str, email: str) -> None: ...
    def role(self, identifier: str) -> str: ...
    def require_admin(self, user) -> None: ...
    def change(self, actor, target: str, new_role: str) -> dict: ...

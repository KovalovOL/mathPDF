from typing import Protocol
from app.reports.models import ReportInput, ReportUpdate


class ReportRepositoryPort(Protocol):
    def event(self, user, event: dict) -> None: ...
    def record(
        self, user, request: ReportInput, spool_on_failure=True, **options
    ) -> dict: ...
    def flush_spool(self) -> None: ...
    def claim_collection(self) -> tuple[dict, str] | None: ...
    def complete_collection(self, report: dict, lease: str, manifest: dict) -> bool: ...
    def retry_collection(self, report: dict, lease: str, error: Exception) -> bool: ...
    def list(self, limit=100, offset=0, status=None) -> list[dict]: ...
    def get(self, identifier: str) -> dict: ...
    def update(self, identifier: str, request: ReportUpdate, actor) -> dict: ...


class ReportBundlePort(Protocol):
    def collect(self, report: dict) -> dict: ...
    def export(self, report: dict) -> bytes: ...
